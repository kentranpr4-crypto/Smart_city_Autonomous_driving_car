#!/usr/bin/env python3
"""Regenerate requirements.lock (hashed) from requirements.in and FAIL if any package is younger than MIN_AGE days.
usage: make_lock.py [TODAY=YYYY-MM-DD]   (needs network; installs nothing)"""
import json, subprocess, sys, urllib.request, datetime as dt, pathlib
TODAY = dt.date.fromisoformat(sys.argv[1]) if len(sys.argv) > 1 else dt.date.today()
cut = TODAY - dt.timedelta(days=14)
py = '.venv/bin/python'
rep = pathlib.Path('.venv/pip-report.json')
subprocess.run([py,'-m','pip','install','--quiet','--dry-run','--ignore-installed','--report',str(rep),'-r','requirements.in'],check=True)
lines, young = [], []
for i in sorted(json.load(open(rep))['install'], key=lambda x: x['metadata']['name'].lower()):
    n, v = i['metadata']['name'], i['metadata']['version']; h = i['download_info']['archive_info']['hashes']['sha256']
    d = json.load(urllib.request.urlopen(f'https://pypi.org/pypi/{n}/{v}/json', timeout=60))
    up = min(dt.date.fromisoformat(f['upload_time'][:10]) for f in d['urls'])
    if up > cut: young.append((n, v, str(up)))
    lines.append(f'{n}=={v} --hash=sha256:{h}')
if young: print('TOO YOUNG:', young); sys.exit(1)
pathlib.Path('requirements.lock').write_text('# Generated by scripts/make_lock.py from requirements.in. Install: pip install --require-hashes -r requirements.lock\n# Hashes pin the wheel resolved on linux/x86_64 cp313; regenerate on another platform.\n' + '\n'.join(lines) + '\n')
print(len(lines), 'packages locked; none younger than 14 days at', TODAY)
